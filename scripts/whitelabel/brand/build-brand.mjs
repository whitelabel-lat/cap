import { execFileSync } from "node:child_process";
import {
	mkdirSync,
	mkdtempSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..", "..");
const publicDir = join(repoRoot, "apps", "web", "public");
const brandDir = join(publicDir, "logos", "zellia");
const pathsFile = join(repoRoot, "packages", "utils", "src", "brand-shapes.ts");

const NAVY = "#023562";
const INK = "#252422";
const CROPS = {
	wordmark: { file: "logo.svg", box: [254.84, 213.55, 951.12, 404.22] },
	wordmarkWhite: {
		file: "logo_dark.svg",
		box: [274.92, 214.58, 909.63, 384.87],
	},
	isotype: {
		file: "logo_thumbnail.svg",
		box: [535.86, 142.71, 401.79, 522.51],
	},
};

const read = (name) => readFileSync(join(here, "src", name), "utf8");
const pathsOf = (svg) =>
	[...svg.matchAll(/<path [^>]*?\bd="([^"]*)"[^>]*?fill="([^"]*)"/g)].map(
		(m) => ({ d: m[1], fill: m[2] }),
	);

const shapes = Object.fromEntries(
	Object.entries(CROPS).map(([key, { file, box }]) => {
		const [body, dot] = pathsOf(read(file));
		return [key, { box, body: body.d, dot: dot.d, dotFill: dot.fill }];
	}),
);

const viewBox = (box) => box.join(" ");
const standalone = (shape, { body, dotFill }) =>
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox(shape.box)}" width="${shape.box[2]}" height="${shape.box[3]}"><path fill="${body}" fill-rule="evenodd" d="${shape.body}"/><path fill="${dotFill}" fill-rule="evenodd" d="${shape.dot}"/></svg>\n`;

mkdirSync(brandDir, { recursive: true });
writeFileSync(
	join(brandDir, "logo.svg"),
	standalone(shapes.wordmark, { body: INK, dotFill: shapes.wordmark.dotFill }),
);
writeFileSync(
	join(brandDir, "logo-dark.svg"),
	standalone(shapes.wordmarkWhite, {
		body: "#ffffff",
		dotFill: shapes.wordmarkWhite.dotFill,
	}),
);
writeFileSync(
	join(brandDir, "isotype.svg"),
	standalone(shapes.isotype, { body: INK, dotFill: shapes.isotype.dotFill }),
);
writeFileSync(
	join(brandDir, "isotype-white.svg"),
	standalone(shapes.isotype, {
		body: "#ffffff",
		dotFill: shapes.isotype.dotFill,
	}),
);
writeFileSync(
	join(publicDir, "cap-icon.svg"),
	standalone(shapes.isotype, { body: INK, dotFill: shapes.isotype.dotFill }),
);
writeFileSync(
	join(publicDir, "logos", "logo-solo.svg"),
	standalone(shapes.isotype, { body: INK, dotFill: shapes.isotype.dotFill }),
);
writeFileSync(
	join(publicDir, "safari-pinned-tab.svg"),
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox(shapes.isotype.box)}"><path fill="#000" fill-rule="evenodd" d="${shapes.isotype.body}"/><path fill="#000" fill-rule="evenodd" d="${shapes.isotype.dot}"/></svg>\n`,
);

const ts = (shape) =>
	`{ viewBox: "${viewBox(shape.box)}", body: "${shape.body}", dot: "${shape.dot}", dotFill: "${shape.dotFill}" }`;
writeFileSync(
	pathsFile,
	`// Generated by scripts/whitelabel/brand/build-brand.mjs from the Zellia brand SVGs. Do not edit by hand.\nexport const ZELLIA_WORDMARK = ${ts(shapes.wordmark)};\n\nexport const ZELLIA_WORDMARK_WHITE = ${ts(shapes.wordmarkWhite)};\n\nexport const ZELLIA_ISOTYPE = ${ts(shapes.isotype)};\n`,
);

execFileSync("bun", ["run", "biome", "format", "--write", pathsFile], {
	cwd: repoRoot,
	stdio: "ignore",
});

const inlineSvg = (shape, { body, style = "" }) =>
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox(shape.box)}" style="${style}"><path fill="${body}" fill-rule="evenodd" d="${shape.body}"/><path fill="${shape.dotFill}" fill-rule="evenodd" d="${shape.dot}"/></svg>`;

const tmp = mkdtempSync(join(tmpdir(), "zellia-brand-"));
const chrome = process.env.CHROME_BIN ?? "google-chrome";

const raster = (out, width, height, body, background = "00000000") => {
	const html = join(tmp, `${Math.random().toString(36).slice(2)}.html`);
	writeFileSync(
		html,
		`<!doctype html><html><head><style>html,body{margin:0;width:${width}px;height:${height}px;overflow:hidden;background:transparent}</style></head><body>${body}</body></html>`,
	);
	execFileSync(chrome, [
		"--headless=new",
		"--no-sandbox",
		"--hide-scrollbars",
		"--force-device-scale-factor=1",
		`--default-background-color=${background}`,
		`--screenshot=${out}`,
		`--window-size=${width},${height}`,
		`file://${html}`,
	]);
};

const scale = (master, size, out) =>
	execFileSync("ffmpeg", [
		"-loglevel",
		"error",
		"-y",
		"-i",
		join(here, "src", master),
		"-vf",
		`scale=${size}:${size}:flags=lanczos`,
		out,
	]);

for (const size of [16, 32]) {
	scale("icon-plain.png", size, join(publicDir, `favicon-${size}x${size}.png`));
}
for (const size of [16, 32, 48]) {
	scale("icon-plain.png", size, join(tmp, `fav-${size}.png`));
}
execFileSync("ffmpeg", [
	"-y",
	"-loglevel",
	"error",
	"-i",
	join(tmp, "fav-16.png"),
	"-i",
	join(tmp, "fav-32.png"),
	"-i",
	join(tmp, "fav-48.png"),
	"-map",
	"0",
	"-map",
	"1",
	"-map",
	"2",
	join(publicDir, "favicon.ico"),
]);
scale("icon-solid.png", 180, join(publicDir, "apple-touch-icon.png"));
scale("icon-plain.png", 192, join(publicDir, "android-chrome-192x192.png"));
scale("icon-plain.png", 512, join(publicDir, "android-chrome-512x512.png"));
scale("icon-tight.png", 150, join(publicDir, "mstile-150x150.png"));

const wordmarkImg = (shape, body, widthPx) =>
	inlineSvg(shape, {
		body,
		style: `width:${widthPx}px;height:auto;display:block`,
	});

raster(
	join(brandDir, "logo-email.png"),
	720,
	Math.round((720 * shapes.wordmark.box[3]) / shapes.wordmark.box[2]),
	wordmarkImg(shapes.wordmark, INK, 720),
);
const interFont = (weight, file) =>
	`@font-face{font-family:"Inter";font-weight:${weight};src:url("${pathToFileURL(join(repoRoot, "apps", "web", "lib", "og", "fonts", file)).href}")}`;
const ogTitle = "Graba, comparte y comenta videos con tu equipo.";

raster(
	join(publicDir, "og.png"),
	1200,
	630,
	`<style>${interFont(400, "Inter-Regular.ttf")}${interFont(500, "Inter-Medium.ttf")}</style><div style="position:relative;width:1200px;height:630px;overflow:hidden;font-family:Inter,sans-serif;color:#111111;background:linear-gradient(135deg,#F5F9FE 0%,#E6EBEF 60%,#AABFD6 140%)"><div style="position:absolute;top:0;left:0;width:1200px;height:10px;background:${NAVY}"></div><div style="position:absolute;left:64px;top:58px">${wordmarkImg(shapes.wordmark, INK, 122)}</div><div style="position:absolute;left:800px;top:70px">${inlineSvg(shapes.isotype, { body: NAVY, style: "height:490px;width:auto;display:block" })}</div><div style="position:absolute;left:64px;top:210px;width:660px;font-size:70px;line-height:1.02;letter-spacing:-2.1px;font-weight:400">${ogTitle}</div><div style="position:absolute;left:64px;bottom:54px;display:flex;align-items:center;gap:12px;font-size:24px;font-weight:500;color:rgba(17,17,17,.74)"><span style="width:12px;height:12px;border-radius:9999px;background:#FC4501"></span>Zellia Clips</div></div>`,
	"F5F9FE",
);

rmSync(tmp, { recursive: true, force: true });
console.log("zellia brand assets regenerated");
